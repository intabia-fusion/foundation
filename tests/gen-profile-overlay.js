#!/usr/bin/env node
//
// Generates docker-compose.profile.yaml from the services this compose project actually has.
// A hardcoded list rots the moment a branch adds or drops a pod - compose then invents an
// image-less service and refuses the whole project.
//
// Usage: docker compose <files> config --format json | node gen-profile-overlay.js > out.yaml

// One-shot containers that exit before any test runs, plus non-Node images where the V8 flags
// would do nothing.
const SKIP = new Set(['db-migrator', 'elastic-plugins'])
const isOurNodeImage = (image) =>
  typeof image === 'string' && image.includes('intabiafusion/') && !image.includes('-go')

let raw = ''
process.stdin.setEncoding('utf8')
process.stdin.on('data', (c) => (raw += c))
process.stdin.on('end', () => {
  let config
  try {
    config = JSON.parse(raw)
  } catch (err) {
    console.error(`gen-profile-overlay: cannot parse compose config (${err.message})`)
    process.exit(1)
  }

  const services = Object.entries(config.services ?? {})
    .filter(([name, def]) => !SKIP.has(name) && isOurNodeImage(def.image))
    .map(([name]) => name)
    .sort()

  if (services.length === 0) {
    console.error('gen-profile-overlay: no intabiafusion services found')
    process.exit(1)
  }

  const head = `# Generated by gen-profile-overlay.js - do not edit, ./prepare-pg.sh --profile rewrites it.
#
# Runs every Node pod under V8's sampling CPU profiler. Profiles are flushed on SIGTERM into
# ./profiles/<service>/ - collect with ./profile-collect.sh, then ./profile-report.sh.
#
# Swap the profiler with PROFILE_NODE_FLAGS, e.g.
#   PROFILE_NODE_FLAGS='--heap-prof --heap-prof-dir' ./prepare-pg.sh --profile
# The service's own directory is appended to the last flag.
x-prof-volumes: &prof-volumes
  - ./profiles:/profiles
  - ./profile-preload.js:/profile-preload.js:ro

services:
`
  const body = services
    .map(
      (s) => `  ${s}:
    environment:
      - PROFILE_DIR=/profiles/${s}
      - NODE_OPTIONS=\${PROFILE_NODE_FLAGS:---cpu-prof --cpu-prof-dir}=/profiles/${s} --require /profile-preload.js
    volumes: *prof-volumes
`
    )
    .join('')

  process.stdout.write(head + body)
  console.error(`gen-profile-overlay: ${services.length} services (${services.join(', ')})`)
})
